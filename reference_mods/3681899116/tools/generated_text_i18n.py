def _format_subjectless(template: str, *args: str) -> str:
    text = template
    try:
        if "{1}" in template:
            first = args[0] if args else ""
            text = template.format("", first)
        elif "{0}" in template:
            first = args[0] if args else ""
            text = template.format(first)
    except Exception:
        text = template
    text = re.sub(r"\s{2,}", " ", text).strip()
    if text and text[0].islower():
        text = text[0].upper() + text[1:]
    return text


def _clean_capture(text: str) -> str:
    return text.strip().rstrip(".")


def _prepend_subject_action(subject: str, action: str) -> str:
    action = action.strip()
    if action.endswith("."):
        action = action[:-1]
    if action and action[0].isupper():
        action = action[0].lower() + action[1:]
    return f"{subject} {action}."


