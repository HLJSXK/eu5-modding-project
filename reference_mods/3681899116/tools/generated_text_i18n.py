def _replace_terms(text: str, terms: dict[str, str]) -> str:
    ascii_word = r"A-Za-z0-9_"
    for old, new in sorted(terms.items(), key=lambda item: len(item[0]), reverse=True):
        pattern = rf"(?<![{ascii_word}]){re.escape(old)}(?![{ascii_word}])"
        text = re.sub(pattern, new, text, flags=re.IGNORECASE)
    return text


def _normalize_engine_text(text: str) -> str:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"\b(Target (?:Location|Character|Country))(\d+)\b", r"\1 \2", text)
    text = re.sub(r"\b(Target Colony)(\d+)\b", r"\1 \2", text)
    text = re.sub(r"\b(Escape Target)(\d+)\b", r"\1 \2", text)
    text = re.sub(r"\bProvince Definition:([^.,;:]+?) Province\b", lambda m: m.group(1).strip(), text)
    text = re.sub(
        r"\b((?:This|Prev|Root Capital|Capital(?: Location| Province)?|Root Location|Source Location|"
        r"Emigration Province|Target Colony(?: \d+)?|Target Province|Target Location(?: \d+)?|"
        r"Target Character(?: \d+)?|Target Country(?: \d+)?|Escape Target(?: \d+)?)) Province Definition\b",
        r"\1",
        text,
    )
    text = re.sub(r"\bProvince Definition\b", "Province", text)
    text = re.sub(r"\bLocation Definition\b", "Location", text)
    text = text.replace("Root Ruler Dynasty", "the dynasty of the current ruler")
    text = text.replace("  ", " ")
    return text.strip()


