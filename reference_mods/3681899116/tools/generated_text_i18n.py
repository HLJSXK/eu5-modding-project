def localize_generated_text(text: str, lang: str) -> str:
    if lang == "english":
        return "\n".join(_normalize_engine_text(line) for line in text.split("\n"))

    locale = LOCALES.get(lang)
    if not locale:
        return text
    return "\n".join(_localize_line(line, locale, lang) for line in text.split("\n"))
