def gui_files(with_glorp):
    from eu5_gui_renderer.gui import _relpath
    from eu5_gui_renderer.paths import GAME
    files: dict[str, Path] = {}
    for root in [GAME] + ([GLORP] if with_glorp else []) + [SOL]:
        for stage in ("loading_screen", "main_menu", "in_game"):
            gui = root / stage / "gui"
            if gui.exists():
                for p in sorted(gui.rglob("*.gui")):
                    files[f"{stage}/{_relpath(p, gui)}"] = p
    return list(files.values()) + [GUI_FILE]


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else WORKSPACE / "ai_gui_assessment/images/living_standard_4sections_20261018"
    out.mkdir(parents=True, exist_ok=True)
    write_sources()

    from PIL import Image
    from eu5_gui_renderer import hud
    from eu5_gui_renderer.data import Evaluator, Formats, Loc, TextIcons
    from eu5_gui_renderer.engine import Engine
    from eu5_gui_renderer.gui import Expander, GuiDB, dump
    from eu5_gui_renderer.textures import TEXTURES

    dbs = {}

    def load_loc(with_glorp):
        loc = Loc()
        paths = list((GLORP / "main_menu/localization/simp_chinese").glob("*.yml")) if with_glorp else []
        for path in paths + [LOC_FILE]:
            for line in path.read_text(encoding="utf-8-sig", errors="replace").splitlines():
                m = Loc.LINE_RE.match(line)
                if m:
                    loc.d[m[1]] = m[2]
        return loc

    def render(state="", with_glorp=False):
        if with_glorp not in dbs:
            dbs[with_glorp] = GuiDB(gui_files(with_glorp))
        db = dbs[with_glorp]
        log = []
        ex = Expander(db, log)
        root = hud.build(db, ex, 1920, 1080)
        node = next(n for n in db.roots[str(GUI_FILE)] if n.is_block())
        row_root = ex.build(node.key, node.value, {}, str(GUI_FILE), node.line)
        root.children.append(row_root)
        loc = load_loc(with_glorp)
        ms = (glorp_mocks() if with_glorp else []) + mocks(state) + hud.mocks()
        eng = Engine(ex, Evaluator(ms, loc, log), loc, Formats(), TextIcons(), 1.0)
        eng.place(root, 0, 0, 1920, 1080)
        img = Image.new("RGBA", (1920, 1080), (29, 35, 42, 255))
        eng.render(root, img)
        sections = [next(e for e in hud.walk(row_root) if e.props.get("name") == f"sol_lshud4_section_{i}")
                    for i in (1, 2, 3, 4)]
        return eng, ex, root, sections, img, log

    def issues_of(log):
        return sorted({x for x in log if re.search(r"sol_ls|SOL_LSHUD|gls_|TYPE ERROR|INVALID|GetGoods", x)})

    strips = []
    for state in STATES:
        eng, ex, root, sections, img, log = render(state)
        strips.append(img.crop((0, 122, 600, 172)))
        tag = state or "_normal"
        if not state:
            img.save(out / "hud.png")
            img.crop((0, 0, 900, 300)).save(out / "row_left.png")
            (out / "tree.txt").write_text("\n".join(dump(root)) + "\n", encoding="utf-8")
        sizes = []
        for i, sec in enumerate(sections, 1):
            tip = ex.build_lazy(sec.tooltipwidget)
            tw, th = eng.measure(tip, None)["hint"]
            sizes.append(f"T{i} {round(tw)}x{round(th)}")
            pad = 14
            alone = Image.new("RGBA", (round(tw) + 2 * pad, round(th) + 2 * pad), (40, 52, 46, 255))
            eng.place(tip, pad, pad, tw, th)
            eng.render(tip, alone)
            alone.save(out / f"tooltip{i}{tag}.png")
            if not state:
                tx = max(4, min(round(sec.x), 1920 - round(tw) - 4))
                ty = round(sec.y + sec.h + 6)
                eng.place(tip, tx, ty, tw, th)
                hover = img.copy()
                eng.render(tip, hover)
                bottom = min(1080, ty + round(th) + 20)
                hover.crop((0, 0, max(900, tx + round(tw) + 20), bottom)).save(out / f"hover{i}.png")
        if not state:
            print("sections:", ", ".join(f"S{i} x={round(s.x)} w={round(s.w)}" for i, s in enumerate(sections, 1)))
        problems = issues_of(log)
        print(f"{tag}: {'; '.join(sizes)}; prototype issues {len(problems)}")
