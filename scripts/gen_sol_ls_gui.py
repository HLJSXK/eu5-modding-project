def headline(base: int, rows: list[tuple[str, str, str]]) -> list[str]:
    """(concept texture, caption key, value expression) x4, written inline.

    Inline rather than a kit type: each figure overrides three different blocks, and a
    shared block name cannot carry four different sets of values (see the kit's note on
    parameterisation).
    """
    i = T(base)
    if base == TOOLTIP_BASE:
        # Funds and the final coefficient already appear in the dashboard. Keep
        # income and savings here, on one compact row, within the screen budget.
        out = [f'{i}hbox = {{ layoutpolicy_horizontal = expanding spacing = 8']
        for concept, label, value in rows[:2]:
            out.extend([
                f'{i}\thbox = {{ spacing = 4',
                f'{i}\t\ticon = {{ size = {{ 20 20 }} texture = "[GetConceptTexture(\'{concept}\')]" }}',
                f'{i}\t\ttext_single = {{ fontsize = 13 text = "{label}" }}',
                f'{i}\t\ttext_single = {{ raw_text = "{value}" }}',
                f'{i}\t}}',
            ])
        out.extend([f'{i}\texpand = {{}}', f'{i}}}'])
        return out
    out = [
        f"{i}hbox = {{",
        f"{i}\tlayoutpolicy_horizontal = expanding",
        f"{i}\tspacing = 6",
    ]
    for concept, label, value in rows:
        out.extend(
            [
                f"{i}\tsol_stat_item = {{",
                f'{i}\t\tblockoverride "sol_stat_icon" {{ texture = "[GetConceptTexture(\'{concept}\')]" }}',
                f'{i}\t\tblockoverride "sol_stat_label" {{ text = "{label}" }}',
                f'{i}\t\tblockoverride "sol_stat_value" {{ raw_text = "{value}" }}',
                f"{i}\t}}",
            ]
        )
    out.append(f"{i}\texpand = {{}}")
    out.append(f"{i}}}")
    return out


def composition(base: int, slices: list[str], legend: list[tuple[str, str]]) -> list[str]:
    """The ring plus its legend.

    Slices carry raw populations, not percentages: the engine normalises a pie, so the
    same block reads correctly for a village of 115 and a realm of 30000.
    """
    i = T(base)
    out = [f"{i}hbox = {{", f"{i}\tlayoutpolicy_horizontal = expanding", f"{i}\tspacing = 10"]
    out.append(f"{i}\tsol_ring = {{")
    for name, value in zip(("nobles", "clergy", "burghers", "commoners", "tribesmen"), slices):
        out.append(f'{i}\t\tblockoverride "sol_slice_{name}" {{ value = "{value}" }}')
    out.append(f"{i}\t}}")
    out.append(f"{i}\tvbox = {{")
    out.append(f"{i}\t\tlayoutpolicy_horizontal = expanding")
    out.append(f"{i}\t\tspacing = 1")
    if base == TOOLTIP_BASE + 1:
        # Two legend entries per row: the same population values as the ring.
        for start in range(0, len(legend), 2):
            out.append(f'{i}\t\thbox = {{ layoutpolicy_horizontal = expanding spacing = 4')
            for estate_label, share in legend[start:start + 2]:
                out.extend([
                    f'{i}\t\t\thbox = {{ size = {{ 176 22 }} spacing = 2',
                    f'{i}\t\t\t\ttext_single = {{ size = {{ 104 22 }} autoresize = no fontsize = 13 align = left|nobaseline text = "{estate_label}" }}',
                    f'{i}\t\t\t\ttext_single = {{ size = {{ 68 22 }} autoresize = no fontsize = 13 align = right|nobaseline raw_text = "{share}" }}',
                    f'{i}\t\t\t}}',
                ])
            out.extend([f'{i}\t\t\texpand = {{}}', f'{i}\t\t}}'])
        out.extend([f'{i}\t}}', f'{i}\texpand = {{}}', f'{i}}}'])
        return out
    for estate_label, share in legend:
        out.append(f"{i}\t\tsol_legend_row = {{")
        out.append(f'{i}\t\t\tblockoverride "sol_legend_name" {{ text = "{estate_label}" }}')
        out.append(f'{i}\t\t\tblockoverride "sol_legend_value" {{ raw_text = "{share}" }}')
        out.append(f"{i}\t\t}}")
    out.append(f"{i}\t}}")
    out.append(f"{i}\texpand = {{}}")
    out.append(f"{i}}}")
    return out


def ledger(base: int, rows: list[tuple[str, list[str]]]) -> list[str]:
    """One row per estate: population, income, upkeep, savings against target.

    The cells go inside blockoverride "sol_ledger_cells" - the kit declares that block
    and a blockoverride replaces a block entirely, so emitting cells beside it would
    append them to the row's own defaults and double every column.

    Stripes are assigned per row rather than by index so an interleaved caption cannot
    shift the parity.
    """
    out = [f"{T(base)}sol_ledger_header = {{}}"]
    for index, (label, values) in enumerate(rows):
        kind = "sol_ledger_row_alt" if index % 2 else "sol_ledger_row"
        i = T(base)
        out.append(f"{i}{kind} = {{")
        out.append(f'{i}\tblockoverride "sol_ledger_label" {{ text = "{label}" }}')
        out.append(f'{i}\tblockoverride "sol_ledger_cells" {{')
        for width, value in zip(LEDGER_COLS[1:], values):
            # autoresize = no is mandatory on a fixed column: text_single inherits
            # autoresize = yes, and autoresize makes the declared size lose to the
            # text's intrinsic width, collapsing every column into its neighbour.
            out.append(
                f'{i}\t\ttext_single = {{ size = {{ {width} 26 }} autoresize = no '
                f'align = center|nobaseline raw_text = "{value}" }}'
            )
        out.append(f"{i}\t}}")
        out.append(f"{i}}}")
    return out


def kv_rows(base: int, rows: list[tuple[str, str]]) -> list[str]:
    """Label + single right-aligned value, striped alternating."""
    if base == TOOLTIP_BASE + 1:
        # Baseline spending is in the hero; retain both raw and final coefficients.
        i = T(base)
        out = [f'{i}hbox = {{ layoutpolicy_horizontal = expanding spacing = 8']
        for label, value in rows[1:]:
            out.extend([
                f'{i}\thbox = {{ spacing = 4',
                f'{i}\t\ttext_single = {{ fontsize = 13 text = "{label}" }}',
                f'{i}\t\ttext_single = {{ raw_text = "{value}" }}',
                f'{i}\t}}',
            ])
        out.extend([f'{i}\texpand = {{}}', f'{i}}}'])
        return out
    out: list[str] = []
    for index, (label, value) in enumerate(rows):
        kind = "sol_kv_row_alt" if index % 2 else "sol_kv_row"
        i = T(base)
        out.append(f"{i}{kind} = {{")
        out.append(f'{i}\tblockoverride "sol_kv_label" {{ text = "{label}" }}')
        out.append(f'{i}\tblockoverride "sol_kv_value" {{ raw_text = "{value}" }}')
        out.append(f"{i}}}")
    return out


def goods_block(base: int, key: str, variable_map: str, scope: str, goods: list[str]) -> list[str]:
    """Caption plus the grouped rows. Kept adjacent: the JTG generator locates the
    caption and rebuilds the vbox that follows it."""
    out = caption(base, key)
    out.append(f"{T(base)}vbox = {{")
    out.append(f"{T(base)}\tlayoutpolicy_horizontal = expanding")
    out.append(f"{T(base)}\tmargin = {{ 10 2 }}")
    out.append(f"{T(base)}\tspacing = 1")
    out.extend(render_group_columns(goods, variable_map, scope, f"{T(base)}\t"))
    out.append(f"{T(base)}}}")
    return out


