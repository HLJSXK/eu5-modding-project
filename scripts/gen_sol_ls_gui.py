#!/usr/bin/env python3
"""Generate the SOL Living Standard GUI surfaces from one spec.

Two surfaces, one visual language:

  in_game/gui/SOL_economy_local.gui                       the location tooltip
  in_game/gui/panels/situation/global_living_standard.gui the country situation panel

Both are organised around the estate rather than the statistic: a player asks "how
are my nobles doing", not "show me column four of the power table". So each estate
owns one ledger row readable straight across, the population mix is a ring instead
of a row of percentages, and goods are grouped by demand group with the group named
on the left of its row.

Outputs, for the stable and standalone targets:

  * both .gui files (no BOM, matching their vanilla sources)
  * SOL_ls_ui_l_english.yml / SOL_ls_ui_l_simp_chinese.yml, the label vocabulary the
    surfaces reference (estate names, ledger headers, group names). UTF-8 BOM, since
    validate.py requires it for .yml.

The goods block is rendered by scripts/sol_goods_ui.py, which the two compatibility
generators also call - they rebuild the same block with their extra goods included.
The handwritten shared kit in stable is also copied to standalone, whose build
deploys its own directory without inheriting stable's GUI definitions.

Usage:
  $env:PYTHONUTF8='1'; & $env:EU5_PYTHON scripts/gen_sol_ls_gui.py
  $env:PYTHONUTF8='1'; & $env:EU5_PYTHON scripts/gen_sol_ls_gui.py --check
"""

