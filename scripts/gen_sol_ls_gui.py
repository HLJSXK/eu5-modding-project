def localization_files(roots: tuple[Path, ...] = TARGETS) -> dict[Path, str]:
    result: dict[Path, str] = {}
    for language, strings in UI_STRINGS.items():
        lines = [f"l_{language}:", " # === SOL Living Standard UI vocabulary ==="]
        for key, value in strings.items():
            lines.append(f' {key}: "{value}"')
        for suffix, value in ESTATE_NAMES[language].items():
            lines.append(f' SOL_ESTATE_{suffix}: "{value}"')
        index = 0 if language == "english" else 1
        for group in GROUP_ORDER:
            lines.append(f" SOL_SUBGROUP_{group.upper()}: \"{GROUP_LABELS[group][index]}\"")
        lines.append("")
        text = "\n".join(lines)
        for root in roots:
            result[
                root / "main_menu" / "localization" / language / f"SOL_ls_ui_l_{language}.yml"
            ] = text
    return result


# -------------------------------------------------------------------------- output
def _goods_names() -> list[str]:
    path = REPO_ROOT / "data" / "goods_weights.csv"
    names: list[str] = []
    with path.open(encoding="utf-8-sig", newline="") as handle:
        next(handle)
        for line in handle:
            name = line.split(",")[0].strip()
            if name and name not in names:
                names.append(name)
    return names


def _outputs(roots: tuple[Path, ...] = TARGETS) -> dict[Path, str]:
    goods = _goods_names()
    if len(goods) != EXPECTED_GOODS or set(goods) != set(PRIMARY_GROUP):
        raise ValueError(
            f"Expected the {EXPECTED_GOODS} grouped SOL goods, found {len(goods)}"
        )
    result: dict[Path, str] = {}
    kit_path = Path("in_game/gui/SOL_living_standard_kit.gui")
    kit = (STABLE / kit_path).read_text(encoding="utf-8-sig")
    for root in roots:
        if root != STABLE:
            result[root / kit_path] = kit
        result[root / "in_game" / "gui" / "SOL_economy_local.gui"] = render_tooltip(goods)
        result[
            root / "in_game" / "gui" / "panels" / "situation" / "global_living_standard.gui"
        ] = render_panel(goods)
    result.update(localization_files(roots))
    return result


def _validate(text: str, label: str) -> None:
    """Guarantees the contracts the compatibility generators depend on."""
    for marker in ("SOL_GUI_SECTION_LOCAL_GOODS", "SOL_GUI_SECTION_COUNTRY_GOODS"):
        if marker not in text:
            continue
        tail = text[text.index(marker) :]
        if "vbox = {" not in tail[:200]:
            raise ValueError(f"{label}: {marker} is not followed by the goods vbox")
    for good in ("wheat", "weaponry", "books"):
        if f'tooltip = "{good}"' not in text and f'@{good}!' not in text:
            raise ValueError(f"{label}: missing a cell for {good}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the SOL Living Standard GUI surfaces.")
    parser.add_argument(
        "--target",
        choices=["stable", "sol_standalone", "all"],
        default="all",
        help="Deploy target to write (default: all).",
    )
    parser.add_argument("--check", action="store_true", help="Check without writing files.")
    args = parser.parse_args()

    roots = ALL_TARGETS if args.target == "all" else (TARGET_ROOTS[args.target],)
    ok = True
    for path, content in _outputs(roots).items():
        relative = path.relative_to(REPO_ROOT)
        # .gui matches its vanilla source (no BOM); .yml must carry one.
        payload = content.encode("utf-8")
        if path.suffix == ".yml":
            payload = UTF8_BOM + payload
        elif path.name != "SOL_living_standard_kit.gui":
            _validate(content, str(relative))
        if args.check:
            current = path.read_bytes() if path.exists() else None
            if current != payload:
                print(f"[FAIL] Out of date: {relative}")
                ok = False
            else:
                print(f"[OK] Up to date: {relative}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(payload)
        print(f"[OK] Written: {relative}")
    if args.check and not ok:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
