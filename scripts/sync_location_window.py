#!/usr/bin/env python3
"""Build SOL's Glorp UI location window with optional CM and GP references."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from gui_14_migration import migrate_location_gui, migrate_location_types
from location_window_integrations import add_great_projects

REPO_ROOT = Path(__file__).resolve().parents[1]
# 3812518640 is the current Glorp UI Workshop snapshot. The older
# 3601047146 directory is retained as historical reference data.
GLORP_ROOT = REPO_ROOT / ".eu5-base" / "reference_mods" / "3812518640"
SOURCE_PATH = GLORP_ROOT / "in_game" / "gui" / "location_window.gui"
SOURCE_METADATA_PATH = GLORP_ROOT / ".metadata" / "metadata.json"
SOURCE_TYPES_PATH = (
    GLORP_ROOT / "in_game" / "gui" / "vanilla" / "cmfg_location_window_vanilla_types.gui"
)
TARGET_PATH = REPO_ROOT / "src" / "stable" / "in_game" / "gui" / "location_window.gui"
TARGET_TYPES_PATH = (
    REPO_ROOT
    / "src"
    / "stable"
    / "in_game"
    / "gui"
    / "vanilla"
    / "cmfg_location_window_vanilla_types.gui"
)

AUTOGENERATED_HEADER = (
    "# @AUTOGENERATED by scripts/sync_location_window.py - do not edit; "
    "source is the current Glorp UI location_window.gui with SOL and optional GP references.\n"
)
AUTOGENERATED_TYPES_HEADER = (
    "# @AUTOGENERATED by scripts/sync_location_window.py - do not edit; "
    "synchronized from the current Glorp UI extracted location types.\n"
)

BUTTON_ANCHOR_RE = re.compile(
    r"(?m)^\s*expand = \{\}\s*\n\s*subheader_unified_icon = \{\s*\n"
    r'\s*visible = "\[HasPopBreakdownIntelOn\(Location\.Self\)\]"'
)

SOL_BUTTON = """							# SOL insertion: shared location living-standard button.
							sol_location_living_standard_button = {}

"""


def verify_glorp_reference() -> str:
    if not SOURCE_PATH.exists():
        raise FileNotFoundError(f"Glorp UI reference file not found: {SOURCE_PATH}")
    if not SOURCE_METADATA_PATH.exists():
        raise FileNotFoundError(f"Glorp UI metadata not found: {SOURCE_METADATA_PATH}")
    if not SOURCE_TYPES_PATH.exists():
        raise FileNotFoundError(f"Glorp UI extracted location types not found: {SOURCE_TYPES_PATH}")

    metadata = json.loads(SOURCE_METADATA_PATH.read_text(encoding="utf-8-sig"))
    if metadata.get("id") != "glorp.ui.rio":
        raise RuntimeError(
            f"Expected Glorp UI metadata id 'glorp.ui.rio', found {metadata.get('id')!r}."
        )

    return str(metadata.get("version", "unknown"))


def generate_location_window(glorp_version: str) -> str:
    source = SOURCE_PATH.read_text(encoding="utf-8-sig")
    source = migrate_location_gui(source, "stable SOL")

    anchor_matches = list(BUTTON_ANCHOR_RE.finditer(source))
    if len(anchor_matches) != 1:
        raise RuntimeError(
            "Expected exactly one SOL button insertion anchor in the Glorp UI demography row, "
            f"found {len(anchor_matches)}."
        )
    insert_at = anchor_matches[0].start()
    text = source[:insert_at] + SOL_BUTTON + source[insert_at:]

    if text.replace(SOL_BUTTON, "", 1) != source:
        raise RuntimeError(
            "Generated location window differs from migrated Glorp UI beyond the SOL button."
        )

    text = add_great_projects(text, expected_queue_actions=6)
    return AUTOGENERATED_HEADER + f"# Glorp UI reference version: {glorp_version}\n" + text


def generate_location_types(glorp_version: str) -> str:
    text = SOURCE_TYPES_PATH.read_text(encoding="utf-8-sig")
    text = migrate_location_types(text, "stable SOL")
    text = "\n".join(line.rstrip() for line in text.splitlines()) + "\n"
    return (
        AUTOGENERATED_TYPES_HEADER
        + f"# Glorp UI reference version: {glorp_version}\n"
        + text
    )


def generate_outputs() -> dict[Path, str]:
    glorp_version = verify_glorp_reference()
    return {
        TARGET_PATH: generate_location_window(glorp_version),
        TARGET_TYPES_PATH: generate_location_types(glorp_version),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="Return non-zero if stable SOL's location window is out of date.",
    )
    args = parser.parse_args()

    generated_outputs = generate_outputs()

    if args.check:
        failed = False
        for path, generated in generated_outputs.items():
            if not path.exists():
                print(f"[FAIL] Missing generated target: {path.relative_to(REPO_ROOT)}")
                failed = True
                continue
            current = path.read_text(encoding="utf-8-sig")
            if current != generated:
                print(f"[FAIL] Out of date: {path.relative_to(REPO_ROOT)}")
                failed = True
                continue
            print(f"[OK] Up to date: {path.relative_to(REPO_ROOT)}")
        if failed:
            print(
                "       Run: $env:PYTHONUTF8='1'; & $env:EU5_PYTHON "
                "scripts/sync_location_window.py"
            )
            return 1
        return 0

    for path, generated in generated_outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(generated, encoding="utf-8")
        print(f"[OK] Generated {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
