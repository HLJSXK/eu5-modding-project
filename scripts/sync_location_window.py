#!/usr/bin/env python3
"""Build SOL's stable location window from vanilla with injected controls."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from gui_14_migration import migrate_location_gui, migrate_location_types
from location_window_integrations import add_great_projects

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATH = (
    REPO_ROOT / ".eu5-base" / "reference_game_files" / "game" / "in_game" / "gui" / "location_window.gui"
)
TARGET_PATH = REPO_ROOT / "src" / "stable" / "in_game" / "gui" / "location_window.gui"
TARGET_TYPES_PATH = REPO_ROOT / "src" / "stable" / "in_game" / "gui" / "vanilla" / "cmfg_location_window_vanilla_types.gui"

AUTOGENERATED_HEADER = (
    "# @AUTOGENERATED by scripts/sync_location_window.py - do not edit; "
    "source is vanilla location_window.gui with SOL and optional GP references.\n"
)
AUTOGENERATED_TYPES_HEADER = (
    "# @AUTOGENERATED by scripts/sync_location_window.py - do not edit; "
    "vanilla types extracted from location_window.gui.\n"
)

BUTTON_ANCHOR_RE = re.compile(
    r"(?m)^\s*expand = \{\}\s*\n\s*subheader_unified_icon = \{\s*\n"
    r'\s*visible = "\[HasPopBreakdownIntelOn\(Location\.Self\)\]"'
)

SOL_BUTTON = """\t\t\t\t\t\t\t# SOL insertion: shared location living-standard button.
\t\t\t\t\t\t\tsol_location_living_standard_button = {}

"""


def _split_vanilla_types(text: str) -> tuple[str, str]:
    """Return the top-level LocationWindowTypes block and the window body."""
    match = re.match(r"(?s)^\s*(types\s+LocationWindowTypes\s*)\{", text)
    if not match:
        raise ValueError("Vanilla location window must begin with LocationWindowTypes")

    opening = text.find("{", match.start(), match.end())
    depth = 0
    quoted = False
    comment = False
    escaped = False
    closing = None
    for index in range(opening, len(text)):
        char = text[index]
        if comment:
            if char == "\n":
                comment = False
            continue
        if quoted:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                quoted = False
            continue
        if char == "#":
            comment = True
        elif char == '"':
            quoted = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                closing = index + 1
                break
    if closing is None:
        raise ValueError("Unbalanced LocationWindowTypes block in vanilla location window")
    return text[match.start():closing], text[closing:].lstrip("\r\n")


def verify_vanilla_reference() -> None:
    if not SOURCE_PATH.exists():
        raise FileNotFoundError(f"Vanilla location window not found: {SOURCE_PATH}")
    source = SOURCE_PATH.read_text(encoding="utf-8-sig")
    _split_vanilla_types(source)
    if "lateralview =" not in source:
        raise RuntimeError("Vanilla location window has no lateralview root")


def generate_location_window() -> str:
    source = migrate_location_gui(SOURCE_PATH.read_text(encoding="utf-8-sig"), "stable SOL")
    _, source = _split_vanilla_types(source)
    anchor_matches = list(BUTTON_ANCHOR_RE.finditer(source))
    if len(anchor_matches) != 1:
        raise RuntimeError(
            "Expected exactly one SOL button insertion anchor in the vanilla demography row, "
            f"found {len(anchor_matches)}."
        )
    insert_at = anchor_matches[0].start()
    source = source[:insert_at] + SOL_BUTTON + source[insert_at:]
    source = add_great_projects(source, expected_queue_actions=6)
    source = "\n".join(line.rstrip() for line in source.splitlines()) + "\n"
    return AUTOGENERATED_HEADER + source


def generate_location_types() -> str:
    types, _ = _split_vanilla_types(SOURCE_PATH.read_text(encoding="utf-8-sig"))
    types = migrate_location_types(types, "vanilla location types")
    types = "\n".join(line.rstrip() for line in types.splitlines()) + "\n"
    return AUTOGENERATED_TYPES_HEADER + types


def generate_outputs() -> dict[Path, str]:
    verify_vanilla_reference()
    return {TARGET_PATH: generate_location_window(), TARGET_TYPES_PATH: generate_location_types()}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Check generated stable location-window files.")
    args = parser.parse_args()
    generated_outputs = generate_outputs()

    if args.check:
        failed = False
        for path, generated in generated_outputs.items():
            current = path.read_text(encoding="utf-8-sig") if path.exists() else None
            if current != generated:
                print(f"[FAIL] Out of date: {path.relative_to(REPO_ROOT)}")
                failed = True
            else:
                print(f"[OK] Up to date: {path.relative_to(REPO_ROOT)}")
        if failed:
            print("       Run: $env:PYTHONUTF8='1'; & $env:EU5_PYTHON scripts/sync_location_window.py")
            return 1
        return 0

    for path, generated in generated_outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(generated, encoding="utf-8")
        print(f"[OK] Generated {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
