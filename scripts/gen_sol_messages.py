#!/usr/bin/env python3
"""Generate the fixed-path message database with vanilla + SOL definitions.

Resolution messages load from main_menu/gui/messagetypes.txt, not arbitrary
GUI .txt files. Preserve every vanilla type when taking ownership of that path.
Other mods owning the same path need a combined compatibility file.
"""

import argparse
import re
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / ".eu5-base/reference_game_files/game/main_menu/gui/messagetypes.txt"
TARGETS = ("stable", "sol_standalone")
MESSAGE_KEY = "PERFORM_global_living_standard_recalculate_ACTION"
SOL_MESSAGE = f"""{MESSAGE_KEY}={{
log=yes
onmap=no
popup=yes
idle=no
option=yes
pausepopup=no
message_category = government
}}
"""


def render() -> str:
    vanilla = BASE.read_text(encoding="utf-8-sig")
    if re.search(rf"(?m)^\s*{re.escape(MESSAGE_KEY)}\s*=", vanilla):
        raise ValueError(f"Vanilla already defines {MESSAGE_KEY}; review the SOL addition")
    return (
        "# @AUTOGENERATED by scripts/gen_sol_messages.py - do not edit.\n"
        "# Fixed-path database: all current vanilla types plus the SOL resolution type.\n"
        + vanilla.rstrip() + "\n\n" + SOL_MESSAGE
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", choices=[*TARGETS, "all"], default="all")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payload = b"\xef\xbb\xbf" + render().encode("utf-8")
    targets = TARGETS if args.target == "all" else (args.target,)
    ok = True
    for target in targets:
        path = ROOT / "src" / target / "main_menu/gui/messagetypes.txt"
        relative = path.relative_to(ROOT)
        if args.check:
            # Preserve the shipped UTF-8 BOM and tolerate Git's CRLF checkout.
            matches = path.exists() and path.read_bytes().replace(b"\r\n", b"\n") == payload
            ok &= matches
            print(f"[{'OK' if matches else 'FAIL'}] {relative}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(payload)
            print(f"[OK] Written: {relative}")
    if not ok:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
