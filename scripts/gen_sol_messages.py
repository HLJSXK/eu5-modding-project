#!/usr/bin/env python3
"""Generate SOL-owned message types for the EU5 1.4.3 additive database.

Message types load from main_menu/gui/messagetypes/*.txt. Include only SOL's
entries; copying vanilla types would register duplicate ids.
"""

import argparse
import re
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / ".eu5-base/reference_game_files/game/main_menu/gui/messagetypes"
TARGETS = ("stable", "sol_standalone")
MESSAGE_PATH = Path("main_menu/gui/messagetypes/SOL_messages.txt")
LEGACY_PATH = Path("main_menu/gui/messagetypes.txt")
GENERATED_HEADER = "# @AUTOGENERATED by scripts/gen_sol_messages.py - do not edit."
MESSAGE_KEY = "PERFORM_global_living_standard_recalculate_ACTION"
SOL_MESSAGE = f"""{MESSAGE_KEY}={{
log=yes
onmap=no
popup=yes
idle=no
option=yes
pausepopup=no
message_category = government
}}
"""


def render() -> str:
    vanilla_files = sorted(BASE.glob("*.txt"))
    if not vanilla_files:
        raise FileNotFoundError(f"Missing EU5 1.4.3 message-type reference: {BASE}")
    for path in vanilla_files:
        vanilla = path.read_text(encoding="utf-8-sig")
        if re.search(rf"(?m)^\s*{re.escape(MESSAGE_KEY)}\s*=", vanilla):
            raise ValueError(f"{path} already defines {MESSAGE_KEY}; review the SOL addition")
    return (
        GENERATED_HEADER + "\n"
        "# EU5 1.4.3 additive database: SOL-owned message types only.\n"
        + SOL_MESSAGE
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", choices=[*TARGETS, "all"], default="all")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    payload = b"\xef\xbb\xbf" + render().encode("utf-8")
    targets = TARGETS if args.target == "all" else (args.target,)
    ok = True
    for target in targets:
        mod_root = ROOT / "src" / target
        path = mod_root / MESSAGE_PATH
        legacy = mod_root / LEGACY_PATH
        relative = path.relative_to(ROOT)
        if args.check:
            # Preserve the shipped UTF-8 BOM and tolerate Git's CRLF checkout.
            matches = path.exists() and path.read_bytes().replace(b"\r\n", b"\n") == payload
            ok &= matches
            print(f"[{'OK' if matches else 'FAIL'}] {relative}")
            if legacy.exists():
                ok = False
                print(f"[FAIL] Obsolete message database: {legacy.relative_to(ROOT)}")
        else:
            if legacy.exists():
                if not legacy.read_text(encoding="utf-8-sig").startswith(GENERATED_HEADER):
                    raise ValueError(f"Migrate unowned legacy message entries manually: {legacy}")
                legacy.unlink()
                print(f"[OK] Removed obsolete generated database: {legacy.relative_to(ROOT)}")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(payload)
            print(f"[OK] Written: {relative}")
    if not ok:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
