"""Living standard (SOL) layer, kept separate from purchasing power.

Two quantities share the same unit (multiples of the baseline basket) but have
different jobs:

* Purchasing power = available (liquid) funds / baseline spending. It is what
  pops can buy, so it alone drives demand: the location raw demand scale, the
  country solver targets and the applied ``local_pop_demand`` modifier.
* Living standard (SOL) = purchasing power + a local bonus. The bonus is
  welfare that does not pass through the market (for example a building's
  service), valued in baseline baskets. It never adds spendable money, so it
  must never feed demand.

Both are stored as ratios: 1 means exactly the baseline basket, 0 means
nothing; displays show ratio - 1. With every bonus at zero, SOL equals
purchasing power.

Aggregation uses SOL-equivalent values (purchasing-power funds plus bonus x
baseline spending), so a country's or estate's SOL is weighted by baseline
spending exactly like its purchasing power.

To add a local bonus, edit ``LOCAL_BONUS_ALL`` (applies to every estate) or
``LOCAL_BONUS_BY_ESTATE`` below and regenerate. Both are script-value bodies
evaluated in location scope.
"""

from __future__ import annotations

import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")


ESTATES = ("nobles", "clergy", "burghers", "commoners", "tribesmen")
METRICS = ("all", *ESTATES)

# Script-value bodies in location scope, in baseline-basket units:
# 0.1 = +10 percentage points of SOL. Negative values are allowed; the
# SOL-equivalent value is floored at zero.
LOCAL_BONUS_ALL = "value = 0"
LOCAL_BONUS_BY_ESTATE = {estate: "value = sol_location_local_sol_bonus_value" for estate in ESTATES}

# Variables owned by this layer. The demand path must not read any of them.
SOL_ONLY_TOKENS = (
    "sol_equivalent",
    "local_sol_bonus",
    "sol_ls_sol",
    "sol_map_living_standard_value",
    "sol_compute_location_living_standard",
)

HEADER = "# @AUTOGENERATED by scripts/gen_sol_economy_effects.py; edit scripts/sol_living_standard_source.py.\n"


def _suffix(metric: str) -> str:
    return "" if metric == "all" else f"_{metric}"


def public_name(metric: str) -> str:
    """Country SOL ratio cached for the HUD tier, ranking and tooltips."""
    return f"sol_ls_sol{_suffix(metric)}"


def location_equivalent(estate: str | None = None) -> str:
    return "sol_location_sol_equivalent" if estate is None else f"sol_location_{estate}_sol_equivalent"


def location_base(estate: str | None = None) -> str:
    return "sol_location_base_total_spending" if estate is None else f"sol_location_{estate}_base_spending"


def render_values() -> str:
    lines = [
        HEADER.rstrip(),
        "",
        "# Local living-standard bonus (location scope), in baseline baskets: 0.1 = +10% SOL.",
        "# It raises SOL only. It adds no funds, so demand never reads it.",
        f"sol_location_local_sol_bonus_value = {{ {LOCAL_BONUS_ALL} }}",
    ]
    for estate in ESTATES:
        lines.append(f"sol_location_{estate}_local_sol_bonus_value = {{ {LOCAL_BONUS_BY_ESTATE[estate]} }}")
    lines += [
        "",
        "# Country scope: national SOL index (ratio - 1) for the HUD tier title; 0 while unset.",
    ]
    name = public_name("all")
    lines.append(
        f"{name}_index_display = {{ value = 0 if = {{ limit = {{ has_variable = {name} }} value = var:{name} subtract = 1 }} }}")
    return "\n".join(lines) + "\n"


def render_effects() -> str:
    lines = [
        "# Living standard (SOL) layer. Reads purchasing-power caches; nothing in the",
        "# demand path reads what it writes. See scripts/sol_living_standard_source.py.",
        "sol_compute_location_living_standard = {",
        "\t# root = location, called at the end of sol_compute_location_pop_demand.",
    ]
    for estate in ESTATES:
        lines.append(
            f"\tset_variable = {{ name = {location_equivalent(estate)} value = {{ "
            f"value = sol_location_{estate}_local_sol_bonus_value multiply = var:{location_base(estate)} "
            f"add = var:sol_location_{estate}_liquid_funds min = 0 }} }}")
    lines.append(f"\tset_variable = {{ name = {location_equivalent()} value = {{ "
                 + " ".join(f"add = var:{location_equivalent(e)}" for e in ESTATES) + " } }")
    lines += ["}", "", "sol_ls_reset_country_living_standard = {"]
    for metric in METRICS:
        suffix = _suffix(metric) or "_all"
        lines += [
            f"\tset_variable = {{ name = sol_ls_sol_equivalent{suffix} value = 0 }}",
            f"\tset_variable = {{ name = sol_ls_sol_base{suffix} value = 0 }}",
        ]
    lines += [
        "}",
        "",
        "sol_ls_accumulate_country_living_standard = {",
        "\t# Location scope, inside the solver preparation pass after sol_compute_location_pop_demand.",
        "\tsave_scope_as = sol_ls_living_standard_location",
        "\towner = {",
        f"\t\tchange_variable = {{ name = sol_ls_sol_equivalent_all add = scope:sol_ls_living_standard_location.var:{location_equivalent()} }}",
        f"\t\tchange_variable = {{ name = sol_ls_sol_base_all add = scope:sol_ls_living_standard_location.var:{location_base()} }}",
    ]
    for estate in ESTATES:
        lines += [
            f"\t\tchange_variable = {{ name = sol_ls_sol_equivalent_{estate} add = scope:sol_ls_living_standard_location.var:{location_equivalent(estate)} }}",
            f"\t\tchange_variable = {{ name = sol_ls_sol_base_{estate} add = scope:sol_ls_living_standard_location.var:{location_base(estate)} }}",
        ]
    lines += ["\t}", "}", "", "sol_ls_finalize_country_living_standard = {"]
    for metric in METRICS:
        suffix = _suffix(metric) or "_all"
        name = public_name(metric)
        lines += [
            # A country or estate without baseline spending has no SOL and is not ranked.
            f"\tremove_variable = {name}",
            "\tif = {",
            f"\t\tlimit = {{ var:sol_ls_sol_base{suffix} > 0 }}",
            f"\t\tset_variable = {{ name = {name} value = {{ value = var:sol_ls_sol_equivalent{suffix} divide = var:sol_ls_sol_base{suffix} }} }}",
            "\t}",
        ]
    lines += ["}", ""]
    return "\n".join(lines)
