"""Living standard: flat + (1 + percent) * annual funds per thousand people.

SOL is an amount, not a ratio. Flat modifiers use annual per-thousand units;
percentages add together and multiply only funds, with a zero-floor multiplier.
Annual estate totals are floored at zero and population weighted. Modifiers
add no spendable funds. Purchasing power alone drives demand.
"""
from __future__ import annotations

import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

