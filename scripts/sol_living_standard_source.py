"""Living standard: annual liquid funds per thousand people + local modifier.

SOL is an amount, not a ratio. Modifiers use the same annual per-thousand
unit and add no spendable funds. Annual estate totals are floored at zero and
aggregated with population weights. Purchasing power alone drives demand.
Edit LOCAL_MODIFIER_ALL or LOCAL_MODIFIER_BY_ESTATE and regenerate.
"""
from __future__ import annotations

import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ESTATES = ("nobles", "clergy", "burghers", "commoners", "tribesmen")
METRICS = ("all", *ESTATES)

# Location script-value bodies: annual gold-equivalent per thousand people.
# Negative modifiers floor SOL at zero; modifiers never add spendable funds.
LOCAL_MODIFIER_ALL = "value = 0"
LOCAL_MODIFIER_BY_ESTATE = {
    estate: "value = sol_location_local_sol_modifier_value" for estate in ESTATES
}
SOL_ONLY_TOKENS = (
    # Enumerate total names: plain "sol_total" also matches legacy income/population helpers.
    *(f"sol_location_{estate}_sol_total" for estate in ESTATES),
    "local_sol_modifier", "sol_location_sol", "sol_ls_sol",
    "sol_map_living_standard_", "sol_compute_location_living_standard",
)
HEADER = "# @AUTOGENERATED by scripts/gen_sol_economy_effects.py; edit scripts/sol_living_standard_source.py.\n"
FEEDBACK_MODIFIERS = (
    "sol_living_standard_migration_modifier",
    "sol_living_standard_low_growth_modifier",
    "sol_living_standard_high_growth_modifier",
)


def render_feedback_modifiers() -> str:
    """Native location modifiers; growth is an additive percentage-point change."""
    lines = [HEADER.rstrip(), ""]
    for name, modifier, value in zip(FEEDBACK_MODIFIERS,
                                    ("local_migration_attraction", "local_population_growth", "local_population_growth"),
                                    ("1", "-0.001", "0.001")):
        lines += [f"{name} = {{", "\tgame_data = { category = location }",
                  f"\t{modifier} = {value}", "}", ""]
    return "\n".join(lines)


def render_feedback_localization(language: str) -> str:
    entries = {
        "english": (
            ("SOL Living Standard: Migration", "Local living standard adds 0.02 migration attraction per SOL, up to +0.5 at 25 SOL."),
            ("SOL Living Standard: Low Population Growth", "Local living standard below 0.1 reduces population growth by 0.1 percentage points."),
            ("SOL Living Standard: High Population Growth", "Local living standard above 10 increases population growth by 0.1 percentage points."),
        ),
        "simp_chinese": (
            ("SOL生活水平：移民吸引力", "当地生活水平每增加1点，移民吸引力增加0.02点；生活水平达到25时封顶为+0.5点。"),
            ("SOL生活水平：人口增长减缓", "当地生活水平低于0.1时，人口增长率降低0.1个百分点。"),
            ("SOL生活水平：人口增长加快", "当地生活水平高于10时，人口增长率提高0.1个百分点。"),
        ),
    }[language]
    lines = [f"l_{language}:"]
    for name, (title, description) in zip(FEEDBACK_MODIFIERS, entries):
        lines += [f' STATIC_MODIFIER_NAME_{name}: "{title}"',
                  f' STATIC_MODIFIER_DESC_{name}: "{description}"']
    return "\n".join(lines) + "\n"


def render_feedback_effects() -> str:
    migration, low, high = FEEDBACK_MODIFIERS
    return f"""# Location scope. Read the scheduled SOL cache in the existing monthly apply pass.
# No new traversal or calculation cadence; an absent cache is neutral.
sol_apply_location_living_standard_modifiers = {{
\tif = {{
\t\tlimit = {{ has_variable = sol_location_sol }}
\t\tadd_location_modifier = {{
\t\t\tmodifier = {migration}
\t\t\tmonths = 1
\t\t\tmode = replace
\t\t\tsize = {{ value = var:sol_location_sol multiply = 0.02 min = 0 max = 0.5 }}
\t\t}}
\t\tif = {{
\t\t\tlimit = {{ var:sol_location_sol < 0.1 }}
\t\t\tadd_location_modifier = {{ modifier = {low} months = 1 mode = replace }}
\t\t\tremove_location_modifier = {high}
\t\t}}
\t\telse_if = {{
\t\t\tlimit = {{ var:sol_location_sol > 10 }}
\t\t\tadd_location_modifier = {{ modifier = {high} months = 1 mode = replace }}
\t\t\tremove_location_modifier = {low}
\t\t}}
\t\telse = {{
\t\t\tremove_location_modifier = {low}
\t\t\tremove_location_modifier = {high}
\t\t}}
\t}}
\telse = {{ sol_clear_location_living_standard_modifiers = yes }}
}}

sol_clear_location_living_standard_modifiers = {{
\tremove_location_modifier = {migration}
\tremove_location_modifier = {low}
\tremove_location_modifier = {high}
}}
"""


def _suffix(metric: str) -> str:
    return "" if metric == "all" else f"_{metric}"


def public_name(metric: str) -> str:
    """Country SOL amount cached for HUD tiers, ranking and tooltips."""
    return f"sol_ls_sol{_suffix(metric)}"


def location_total(estate: str | None = None) -> str:
    return "sol_location_sol_total" if estate is None else f"sol_location_{estate}_sol_total"


def population(estate: str) -> str:
    return "local_commoner_population" if estate == "commoners" else f"num_pop_type:{estate}"


def render_values() -> str:
    lines = [
        HEADER.rstrip(), "",
        "# Location SOL modifier: annual gold-equivalent per thousand, not baseline baskets.",
        "# Raises SOL only; adds no funds and is never read by demand.",
        f"sol_location_local_sol_modifier_value = {{ {LOCAL_MODIFIER_ALL} }}",
    ]
    for estate in ESTATES:
        lines.append(f"sol_location_{estate}_local_sol_modifier_value = {{ {LOCAL_MODIFIER_BY_ESTATE[estate]} }}")
    lines += ["", "# Country SOL amount; 0 while unset. No ratio-to-percent conversion.",
              "sol_ls_sol_display = { value = 0 if = { limit = { has_variable = sol_ls_sol } value = var:sol_ls_sol } }"]
    return "\n".join(lines) + "\n"


def render_effects() -> str:
    lines = [
        "# Living standard: annual funds per thousand + modifier, population weighted.",
        "# Annual SOL totals are accounting amounts, never spendable funds or demand inputs.",
        "sol_compute_location_living_standard = {",
        "\t# Location scope, last step of sol_compute_location_pop_demand.",
    ]
    for estate in ESTATES:
        lines.append(
            f"\tset_variable = {{ name = {location_total(estate)} value = {{ "
            f"value = sol_location_{estate}_local_sol_modifier_value multiply = {population(estate)} "
            f"add = {{ value = var:sol_location_{estate}_liquid_funds multiply = sol_ls_annualization_factor }} min = 0 }} }}")
    lines.append(f"\tset_variable = {{ name = {location_total()} value = {{ "
                 + " ".join(f"add = var:{location_total(e)}" for e in ESTATES) + " } }")
    lines += [
        "\tremove_variable = sol_location_sol", "\tif = {",
        "\t\tlimit = { local_sol_population_sum > 0 }",
        "\t\tset_variable = { name = sol_location_sol value = { value = var:sol_location_sol_total divide = local_sol_population_sum } }",
        "\t}", "}", "", "sol_ls_reset_country_living_standard = {",
    ]
    for metric in METRICS:
        lines.append(f"\tset_variable = {{ name = sol_ls_sol_total_{metric} value = 0 }}")
    lines += [
        "}", "", "sol_ls_accumulate_country_living_standard = {",
        "\t# Existing preparation pass, immediately after population/income accumulation.",
        "\tsave_scope_as = sol_ls_living_standard_location", "\towner = {",
    ]
    for metric in METRICS:
        total = location_total(None if metric == "all" else metric)
        lines.append(f"\t\tchange_variable = {{ name = sol_ls_sol_total_{metric} add = scope:sol_ls_living_standard_location.var:{total} }}")
    lines += ["\t}", "}", "", "sol_ls_finalize_country_living_standard = {",
              "\t# sol_ls_pop_* is complete in both solver paths; income finalize does not reset it."]
    for metric in METRICS:
        name = public_name(metric)
        lines += [
            f"\tremove_variable = {name}", "\tif = {",
            f"\t\tlimit = {{ var:sol_ls_pop_{metric} > 0 }}",
            f"\t\tset_variable = {{ name = {name} value = {{ value = var:sol_ls_sol_total_{metric} divide = var:sol_ls_pop_{metric} }} }}",
            "\t}",
        ]
    lines += ["}", ""]
    return "\n".join(lines) + "\n" + render_feedback_effects()
