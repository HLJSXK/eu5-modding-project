def render_modifier_types() -> str:
    lines = [HEADER.rstrip(), ""]
    for name, display in ((FLAT_MODIFIER, "decimals = 2"), (PERCENT_MODIFIER, "percent = yes")):
        lines += [f"{name} = {{", f"\t{display}", "\tgame_data = { category = location }", "}", ""]
    return "\n".join(lines)


def render_modifier_icons() -> str:
    lines = [HEADER.rstrip(), ""]
    for name in (FLAT_MODIFIER, PERCENT_MODIFIER):
        lines += [f"{name} = {{",
                  '\tpositive = "gfx/interface/icons/modifier_types/sol_living_standard.dds"',
                  '\tnegative = "gfx/interface/icons/modifier_types/sol_living_standard.dds"', "}", ""]
