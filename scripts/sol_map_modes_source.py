"""Emit SOL's local income/purchasing-power and country substitution/ranking maps.

The raw location caches precede the country solver. Never substitute its final
demand scale or applied modifier for either local map's display value.
"""
from __future__ import annotations

import re
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

MAP_MODES = ("sol_living_standard", "sol_purchasing_power", "sol_substitution", "sol_ranking")
LOW = "rgb { 210 70 55 }"
MID = "rgb { 235 205 100 }"
HIGH = "rgb { 50 180 90 }"
HEADER = "# Generated by scripts/gen_sol_lshud.py; edit scripts/sol_map_modes_source.py.\n"


def _lerp(low: str, high: str, factor: str) -> str:
    return f"lerp = {{ min_color = {low} max_color = {high} factor = {{ {factor} }} }}"


def _mode(name: str, color: str, tooltip: str, *, country: bool = False,
          legends: tuple[tuple[str, str], ...] = (), enabled: bool = False) -> str:
    if enabled:
        # Preserve stable's CMF map-coloring switch without adding a CMF dependency to standalone.
        color = color.replace("limit = { ", "limit = { sol_map_is_on = yes ", 1)
    context = "country" if country else "location"
    legend = "\n".join(f'\tlegend_key = {{ desc = "{key}" color = {value} }}' for key, value in legends)
    return f"""
{name} = {{
\tmap_color = {{
{color}
\t}}
{legend}
\ttooltip_key = {{
{tooltip}
\t}}
\tsmall_map_names = {context}
\tmedium_map_names = {context}
\tlarge_map_names = {context}
\tsmall_tooltip_context = {context}
\tmedium_tooltip_context = {context}
\tlarge_tooltip_context = {context}
\tfill_in_impassable = yes
\tenable_snow = no
\tflatmap_behaviour = always
\tuse_fow = no
\tcategory = economy
\tindex = {MAP_MODES.index(name)}
\tmap_markers = {{ all = no }}
\tgradient_parameters = {{
\t\tzoom_step = 2
\t\tgradient_alpha_inside = 1
\t\tgradient_alpha_outside = 1
\t\tgradient_width = 0.25
\t\tgradient_color_mult = 0.9
\t\tedge_width = 0
\t\tedge_sharpness = 0.01
\t\tedge_alpha = 0
\t\tedge_color_mult = 0
\t\tbefore_lighting_blend = 0.5
\t\tafter_lighting_blend = 0.5
\t}}
\tcolor_refresh_counters = {{ Month }}
\tcolor_and_names_refresh_counters = {{ Month LocationOwnerChanged CountryStatus }}
}}
"""


def render_map_modes(*, standalone: bool = False) -> str:
    owned = "is_land = yes has_owner = yes"
    income_ready = f"{owned} has_variable = gls_location_actual_per_capita_spending"
    income_color = f"""\t\t# Cached local liquid funds / local population, independent of solver beta.
\t\tif = {{ limit = {{ {income_ready} }}
\t\t\t{_lerp('define:NMapColors|MAP_COLOR_LOW', 'define:NMapColors|MAP_COLOR_HIGH', 'value = gls_location_color_factor')}
\t\t}}
\t\telse = {{ value = define:NMapColors|DEFAULT_COLOR }}"""
    income_tooltip = []
    for i, (threshold, suffix) in enumerate(((0.5, "HIGH"), (0.1, "MID"), (0.01, "LOW"))):
        income_tooltip.append(
            f"\t\t{'if' if i == 0 else 'else_if'} = {{ limit = {{ {income_ready} var:gls_location_actual_per_capita_spending >= {threshold} }} value = MAPMODE_SOL_LIVING_STANDARD_TT_{suffix} }}")
    income_tooltip += [
        f"\t\telse_if = {{ limit = {{ {income_ready} }} value = MAPMODE_SOL_LIVING_STANDARD_TT_VERY_LOW }}",
        f"\t\telse_if = {{ limit = {{ {owned} }} value = MAPMODE_SOL_LIVING_STANDARD_TT_UNCACHED }}",
        "\t\telse = { value = MAPMODE_SOL_LIVING_STANDARD_TT_WATER }",
    ]
    income = _mode(MAP_MODES[0], income_color, "\n".join(income_tooltip), legends=(
        ("GLS_MAP_LEGEND_HIGH", "define:NMapColors|MAP_COLOR_HIGH"),
        ("GLS_MAP_LEGEND_MID", "define:NMapColors|MAP_COLOR_MID"),
        ("GLS_MAP_LEGEND_LOW", "define:NMapColors|MAP_COLOR_LOW")), enabled=not standalone)

    power_ready = (f"{owned} has_variable = sol_location_liquid_funds "
                   "has_variable = sol_location_base_total_spending")
    power_color = f"""\t\t# Alpha - 1, with the same -100% / 0% / +200% anchors as the HUD.
\t\tif = {{ limit = {{ {power_ready} var:sol_location_base_total_spending > 0 }}
\t\t\tif = {{ limit = {{ sol_map_purchasing_power_value < 0 }}
\t\t\t\t{_lerp(LOW, MID, 'value = sol_map_purchasing_power_value add = 1 min = 0 max = 1')}
\t\t\t}}
\t\t\telse = {{ {_lerp(MID, HIGH, 'value = sol_map_purchasing_power_value divide = 2 min = 0 max = 1')} }}
\t\t}}
\t\telse = {{ value = define:NMapColors|DEFAULT_COLOR }}"""
    power = _mode(MAP_MODES[1], power_color, f"""\t\tif = {{ limit = {{ {power_ready} var:sol_location_base_total_spending > 0 }} value = SOL_MAP_POWER_TT }}
\t\telse_if = {{ limit = {{ {power_ready} }} value = SOL_MAP_POWER_NO_CONSUMPTION }}
\t\telse = {{ value = SOL_MAP_PENDING }}""", legends=(
        ("SOL_MAP_POWER_HIGH", HIGH), ("SOL_MAP_POWER_MID", MID), ("SOL_MAP_POWER_LOW", LOW)), enabled=not standalone)

    substitution = _mode(MAP_MODES[2], f"""\t\tif = {{ limit = {{ {owned} }} value = owner.country_color }}
\t\telse = {{ value = define:NMapColors|DEFAULT_COLOR }}""",
        f"\t\tif = {{ limit = {{ {owned} }} value = SOL_MAP_SUBSTITUTION_TT }}\n\t\telse = {{ value = SOL_MAP_PENDING }}", country=True, enabled=not standalone)
    ranking = _mode(MAP_MODES[3], f"""\t\tif = {{ limit = {{ {owned} owner = {{ has_variable = sol_ls_rank has_variable = sol_ls_percentile }} }}
\t\t\t{_lerp(LOW, HIGH, 'value = owner.sol_map_rank_color_factor')}
\t\t}}
\t\telse = {{ value = define:NMapColors|DEFAULT_COLOR }}""",
        f"\t\tif = {{ limit = {{ {owned} owner = {{ has_variable = sol_ls_rank }} }} value = SOL_MAP_RANK_TT }}\n\t\telse = {{ value = SOL_MAP_PENDING }}",
        country=True, legends=(("SOL_MAP_RANK_HIGH", HIGH), ("SOL_MAP_RANK_LOW", LOW)), enabled=not standalone)
    return HEADER + income + power + substitution + ranking


def render_map_values() -> str:
    return HEADER + """
# Location scope. Do not read sol_location_final_demand_scale or modifier size.
sol_map_purchasing_power_value = {
\tvalue = 0
\tif = {
\t\tlimit = { has_variable = sol_location_liquid_funds has_variable = sol_location_base_total_spending var:sol_location_base_total_spending > 0 }
\t\tvalue = var:sol_location_liquid_funds
\t\tdivide = var:sol_location_base_total_spending
\t\tsubtract = 1
\t}
}

# Country scope. The cached percentile already maps best -> 1 and worst -> 0.
sol_map_rank_color_factor = {
\tvalue = 0
\tif = {
\t\tlimit = { has_variable = sol_ls_rank has_variable = sol_ls_percentile }
\t\tvalue = var:sol_ls_percentile
\t\tif = { limit = { has_global_variable = sol_ls_rank_count global_var:sol_ls_rank_count = 1 } value = 1 }
\t\tmin = 0
\t\tmax = 1
\t}
}
"""


def render_map_tooltips(source, localization_keys: set[str]) -> str:
    """Retain a primary Scope while nested ranking rows bind peer Country objects."""
    text = HEADER
    for idx, mode, builder in ((3, MAP_MODES[2], source.tooltip_goods), (4, MAP_MODES[3], source.tooltip_rank)):
        template = builder().replace(f"SOL_LSHUD4_tooltip_{idx}", f"SOL_MAP_tooltip_{idx}")
        template = template.replace("Player", "Scope.GetCountry")
        # Localized strings are bindings too: their player references need the same adapter.
        template = re.sub(r"\b(?:" + "|".join(sorted(localization_keys, key=len, reverse=True)) + r")\b",
                          lambda m: m[0] + "_MAP", template)
        template = template.replace(f'text = "SOL_LSHUD4_T{idx}_TITLE"',
                                    f'text = "SOL_MAP_COUNTRY_T{idx}_TITLE"')
        text += template
        text += f"""
container = {{
\tname = "CountryMapTooltip_{mode}"
\talwaystransparent = no
\tcontainer = {{
\t\tvisible = "[Country.IsValid]"
\t\tdatacontext = "[Country.MakeScope]"
\t\tusing = SOL_MAP_tooltip_{idx}
\t}}
}}
"""
    text += """
container = {
\tname = "LocationMapTooltip_sol_purchasing_power"
\talwaystransparent = no
\tcontainer = {
\t\tvisible = "[Location.HasOwner]"
\t\tusing = StandardofLiving_tooltip
\t}
}
"""
    return text


