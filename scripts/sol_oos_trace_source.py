"""Read-only OOS file tracing; never use CMF maps or random selectors here."""
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

# Instrument complete effect boundaries after generation, preserving every original
# statement and its order. Compatibility targets inherit these base effects.
BOUNDARIES = {
    "sol_refresh_market_pop_demand_maps": ("market_refresh", "global"),
    "sol_solve_country_pop_demand": ("solve", "country"),
    "sol_apply_local_pop_demand_modifiers": ("apply", "country"),
    "gls_full_refresh_country": ("country_refresh", "country"),
    "gls_recalculate_global_living_standard": ("world_refresh", "global"),
}
METRICS = (
    "sol_country_demand_solve_status",
    "sol_country_demand_selected_strategy",
    "sol_country_base_spending_total",
    "sol_ls_sol",
)


def instrument(text: str) -> str:
    """Insert paired calls at known top-level boundaries, without rewriting bodies."""
    lines = text.splitlines()
    output = []
    active = None
    seen = set()
    for line in lines:
        if active and line == "}":
            phase, kind = active
            output.append(f"\tsol_oos_trace_{kind} = {{ stage = {phase}_end }}")
            active = None
        output.append(line)
        for name, (phase, kind) in BOUNDARIES.items():
            if line == f"{name} = {{":
                if name in seen:
                    raise ValueError(f"Duplicate trace boundary: {name}")
                seen.add(name)
                active = (phase, kind)
                output.append(f"\tsol_oos_trace_{kind} = {{ stage = {phase}_begin }}")
    if active or seen != set(BOUNDARIES):
        raise ValueError(f"Missing/unclosed trace boundaries: {set(BOUNDARIES) - seen}")
    return "\n".join(output) + "\n"


def render_effects() -> str:
    lines = [
        "# @AUTOGENERATED by scripts/gen_sol_economy_effects.py",
        "# Default OFF; package builder enables the separate trigger in an exported copy.",
        "# No persistent writes, random calls, or gameplay effects. Saved scope is execution-local.",
        "sol_oos_trace_global = {",
        "\tif = {",
        "\t\tlimit = { sol_oos_trace_is_enabled = yes }",
        # Pipes outside [] are localization formatting, not safe delimiters.
        '\t\tdebug_log = "SOL_OOS;2;$stage$;GLOBAL;[GetDateString];event"',
        "\t\tdebug_log_date = yes",
        "\t}",
        "}",
        "",
        "sol_oos_trace_country = {",
        "\tif = {",
        "\t\tlimit = { sol_oos_trace_is_enabled = yes is_human = yes }",
        "\t\tsave_scope_as = sol_oos_trace_subject",
    ]
    # GetTag has an unregistered return type in the engine data API; use CString.
    subject = "SCOPE.sCountry('sol_oos_trace_subject')"
    prefix = f"SOL_OOS;2;$stage$;[{subject}.GetTagAndName];[GetDateString]"
    lines += [f'\t\tdebug_log = "{prefix};event"', "\t\tdebug_log_scopes = no"]
    for metric in METRICS:
        expression = f"[{subject}.MakeScope.GetVariable('{metric}').GetValue|V5]"
        lines += [
            "\t\tif = {",
            f"\t\t\tlimit = {{ has_variable = {metric} }}",
            f'\t\t\tdebug_log = "{prefix};{metric}={expression}"',
            "\t\t}",
            f'\t\telse = {{ debug_log = "{prefix};{metric}=MISSING" }}',
        ]
    lines += ["\t}", "}"]
    return "\n".join(lines) + "\n"
