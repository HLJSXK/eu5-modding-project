"""Python emitters for the generated SOL economy effects.

The Jomini output is built by executable Python functions. Repeated structures
are expanded from data by the calling generator; no external effect-source
text files are read at runtime.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from typing import Callable, List, Sequence

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")


@dataclass
class ScriptWriter:
    """Small line-oriented writer for deterministic Clausewitz/Jomini output."""

    lines: List[str]

    def __init__(self) -> None:
        self.lines = []

    def extend(self, lines: Sequence[str]) -> None:
        self.lines.extend(lines)

    def line(self, text: str = "") -> None:
        self.lines.append(text)

    def render(self) -> str:
        return "\n".join(self.lines).strip() + "\n"


