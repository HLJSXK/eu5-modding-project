def _render_location_gui() -> str:
    text = _read(MNT_LOCATION_GUI)
    text = _replace_once(
        text,
        'raw_text = "[Location.GetTotalIncome|g2]@income!"',
        'raw_text = "[Location.MakeScope.ScriptValue(\'local_sol_total_income\')|g2]@income!"',
        "M&T location income",
    )
    matches = list(BUTTON_ANCHOR_RE.finditer(text))
    if len(matches) != 1:
        raise ValueError(f"Expected one M&T location button anchor, found {len(matches)}")
    text = text[: matches[0].start()] + SOL_BUTTON + text[matches[0].start() :]
    return GENERATED_HEADER + text


def _render_outputs() -> Dict[Path, str]:
    sol_targets = _load_sol_targets()
    vanilla_goods = load_vanilla_goods()
    vanilla_prices = {good: _decimal(data["price"]) for good, data in vanilla_goods.items()}
    mnt_goods_blocks_list = _blocks_in_tree(MNT_GOODS_ROOT)
    mnt_goods_blocks: Dict[str, Block] = {}
    for good in sol_targets:
        mnt_goods_blocks[good] = _unique_block(mnt_goods_blocks_list, good, "M&T good")
    if len(sol_targets) != 55:
        raise ValueError(f"Expected 55 SOL demand goods, found {len(sol_targets)}")
    quantities = _compat_quantities(sol_targets, vanilla_prices, mnt_goods_blocks)
    _validate_demand_invariants(sol_targets, quantities, vanilla_prices, mnt_goods_blocks)
    values, refresh = _render_values_and_refresh(quantities, mnt_goods_blocks)

    return {
        GOODS_OUTPUT: _render_goods(sol_targets, quantities, mnt_goods_blocks),
        VALUES_OUTPUT: values,
        EFFECTS_OUTPUT: _render_effects(refresh),
        CMM_OUTPUT: _render_cmm(),
        CMM_VALUES_OUTPUT: _render_cmm_values(),
        CMM_SCRIPTED_GUI_OUTPUT: _render_cmm_scripted_guis(),
        TRIGGERS_OUTPUT: _render_disabled_triggers(),
        ENGLISH_CMM_LOC_OUTPUT: _render_cmm_localization("english"),
        CHINESE_CMM_LOC_OUTPUT: _render_cmm_localization("simp_chinese"),
        PRICES_OUTPUT: _render_authority_objects(
            STABLE_PRICES,
            VANILLA_PRICES_ROOT,
            MNT_PRICES_ROOT,
            "# Remove every SOL price rebalance; M&T wins shared keys and vanilla wins the rest.",
        ),
        STATIC_OUTPUT: _render_authority_objects(
            STABLE_STATIC_MODIFIERS,
            VANILLA_STATIC_ROOT,
            MNT_STATIC_ROOT,
            "# Remove every SOL economic static delta; M&T wins shared keys and vanilla wins the rest.",
        ),
        CABINET_OUTPUT: _render_decoupled_action(
            STABLE_CABINET,
            "reduce_war_exhaustion",
            "# Retain SOL's wartime restriction without the removed economic master switch.",
        ),
        COLONIAL_OUTPUT: _render_decoupled_action(
            STABLE_COLONIAL,
            "create_colonial_charter",
            "# Retain SOL's colonial restrictions without the removed economic master switch.",
        ),
        LOCATION_GUI_OUTPUT: _render_location_gui(),
    }


def _check(outputs: Dict[Path, str]) -> bool:
    ok = True
    for path, expected in outputs.items():
        relative = path.relative_to(REPO_ROOT)
        if not path.exists():
            print(f"[FAIL] Missing generated target: {relative}")
            ok = False
            continue
        if path.read_bytes()[:3] != UTF8_BOM:
            print(f"[FAIL] Missing UTF-8 BOM: {relative}")
            ok = False
            continue
        if _read(path) != expected:
            print(f"[FAIL] Out of date: {relative}")
            ok = False
            continue
        print(f"[OK] Up to date: {relative}")
    return ok


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate SOL-M&T compatibility overrides.")
    parser.add_argument("--check", action="store_true", help="Check outputs without writing files.")
    args = parser.parse_args()

    outputs = _render_outputs()
    if args.check:
        raise SystemExit(0 if _check(outputs) else 1)

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(UTF8_BOM + content.encode("utf-8"))
        print(f"[gen_sol_mnt_compat] Wrote {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
