@dataclass(frozen=True)
class Block:
    key: str
    body: str
    operation: str
    source: Path


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig")


def _decimal(value: str | float | Decimal) -> Decimal:
    if isinstance(value, Decimal):
        return value
    return Decimal(str(value))


def _round_quantity(value: Decimal) -> Decimal:
    return value.quantize(QUANTUM, rounding=ROUND_HALF_UP)


def _format_decimal(value: Decimal) -> str:
    rounded = _round_quantity(value)
    if rounded == 0:
        return "0"
    return format(rounded, "f").rstrip("0").rstrip(".")


def _parse_top_level_blocks(text: str, source: Path) -> List[Block]:
    blocks: List[Block] = []
    index = 0
    while index < len(text):
        while index < len(text) and text[index] in " \t\r\n":
            index += 1
        if index >= len(text):
            break
        if text[index] == "#":
            newline = text.find("\n", index)
            index = len(text) if newline < 0 else newline + 1
            continue
        match = re.match(
            r"(?:(?P<operation>(?:TRY_)?(?:INJECT|REPLACE)):)?"
            r"(?P<key>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*\{",
            text[index:],
        )
        if not match:
            newline = text.find("\n", index)
            index = len(text) if newline < 0 else newline + 1
            continue
        brace_start = index + match.end() - 1
        body, brace_end = _collect_brace_block(text, brace_start)
        blocks.append(
            Block(
                key=match.group("key"),
                body=body,
                operation=match.group("operation") or "",
                source=source,
            )
        )
        index = brace_end + 1
    return blocks


def _blocks_in_file(path: Path) -> List[Block]:
    return _parse_top_level_blocks(_read(path), path)


def _blocks_in_tree(root: Path) -> List[Block]:
    blocks: List[Block] = []
    for path in sorted(root.rglob("*.txt")):
        if path.name.lower() == "readme.txt":
            continue
        blocks.extend(_blocks_in_file(path))
    return blocks


def _unique_block(blocks: Iterable[Block], key: str, label: str) -> Block:
    matches = [block for block in blocks if block.key == key]
    if len(matches) != 1:
        locations = [str(block.source.relative_to(REPO_ROOT)) for block in matches]
        raise ValueError(f"Expected one {label} block for {key}, found {len(matches)}: {locations}")
    return matches[0]


def _optional_unique_block(blocks: Iterable[Block], key: str, label: str) -> Optional[Block]:
    matches = [block for block in blocks if block.key == key]
    if len(matches) > 1:
        locations = [str(block.source.relative_to(REPO_ROOT)) for block in matches]
        raise ValueError(f"Expected at most one {label} block for {key}, found {len(matches)}: {locations}")
    return matches[0] if matches else None


def _field_spans(body: str, field: str, block: bool) -> List[Tuple[int, int]]:
    suffix = r"\s*=\s*\{" if block else r"\s*=\s*[^\r\n#}]+(?:\s*#.*)?"
    pattern = re.compile(rf"(?m)^[ \t]*{re.escape(field)}{suffix}[ \t]*(?:\r?\n|$)")
    spans: List[Tuple[int, int]] = []
    for match in pattern.finditer(body):
        depth = body[: match.start()].count("{") - body[: match.start()].count("}")
        if depth != 0:
            continue
        if block:
            brace_start = body.index("{", match.start())
            _inner, brace_end = _collect_brace_block(body, brace_start)
            end = brace_end + 1
            while end < len(body) and body[end] in " \t":
                end += 1
            if end < len(body) and body[end] == "#":
                newline = body.find("\n", end)
                end = len(body) if newline < 0 else newline + 1
            elif end < len(body) and body[end] == "\r":
                end += 1
                if end < len(body) and body[end] == "\n":
                    end += 1
            elif end < len(body) and body[end] == "\n":
                end += 1
            spans.append((match.start(), end))
        else:
            spans.append((match.start(), match.end()))
    return spans


def _remove_fields(body: str, fields: Sequence[Tuple[str, bool]]) -> str:
    spans: List[Tuple[int, int]] = []
    for field, is_block in fields:
        spans.extend(_field_spans(body, field, is_block))
    for start, end in sorted(spans, reverse=True):
        body = body[:start] + body[end:]
    return body


DEMAND_FIELDS = (
    ("demand_add", True),
    ("demand_multiply", True),
    ("development_threshold", False),
    ("wealth_impact_threshold", True),
)


def _simple_block_values(body: str, field: str) -> Dict[str, Decimal]:
    spans = _field_spans(body, field, True)
    if not spans:
        return {}
    if len(spans) != 1:
        raise ValueError(f"Expected one {field} block")
    start, _end = spans[0]
    brace_start = body.index("{", start)
    inner, _brace_end = _collect_brace_block(body, brace_start)
    result: Dict[str, Decimal] = {}
    for match in re.finditer(
        r"(?m)^[ \t]*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(-?(?:\d+(?:\.\d*)?|\.\d+))",
        inner,
    ):
        result[match.group(1)] = Decimal(match.group(2))
    return result


def _expand_group_values(values: Dict[str, Decimal], multiply: bool) -> Dict[str, Decimal]:
    result = {pop_type: Decimal("1") if multiply else Decimal("0") for pop_type in ALL_POP_TYPES}
    ordered_keys = ["all", "upper", "commoners"] + [
        key for key in values if key not in {"all", "upper", "commoners"}
    ]
    for key in ordered_keys:
        if key not in values:
            continue
        if key == "all":
            targets = ALL_POP_TYPES
        elif key == "upper":
            targets = UPPER_TYPES
        elif key == "commoners":
            targets = COMMONER_TYPES
        elif key in ALL_POP_TYPES:
            targets = (key,)
        else:
            raise ValueError(f"Unsupported M&T demand group: {key}")
        for pop_type in targets:
            if multiply:
                result[pop_type] *= values[key]
            else:
                result[pop_type] += values[key]
    return result


def _final_pop_demand(body: str) -> Dict[str, Decimal]:
    additions = _expand_group_values(_simple_block_values(body, "demand_add"), multiply=False)
    multipliers = _expand_group_values(_simple_block_values(body, "demand_multiply"), multiply=True)
    return {pop_type: additions[pop_type] * multipliers[pop_type] for pop_type in ALL_POP_TYPES}


def _default_price(body: str, key: str) -> Decimal:
    match = re.search(
        r"(?m)^[ \t]*default_market_price\s*=\s*(-?(?:\d+(?:\.\d*)?|\.\d+))",
        body,
    )
    if not match:
        raise ValueError(f"default_market_price missing for {key}")
    price = Decimal(match.group(1))
    if price <= 0:
        raise ValueError(f"default_market_price must be positive for {key}")
    return price


def _load_sol_targets() -> Dict[str, Dict[str, Decimal]]:
    result: Dict[str, Dict[str, Decimal]] = {}
    with TARGET_DEMAND_CSV.open(encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            result[row["good"]] = {
                pop_type: Decimal(row.get(pop_type, "0") or "0") for pop_type in POP_TYPES
            }
    return result


def _compat_quantities(
    sol_targets: Dict[str, Dict[str, Decimal]],
    vanilla_prices: Dict[str, Decimal],
    mnt_blocks: Dict[str, Block],
) -> Dict[str, Dict[str, Decimal]]:
    quantities: Dict[str, Dict[str, Decimal]] = {}
    for good, target in sol_targets.items():
        if good not in mnt_blocks:
            raise ValueError(f"M&T goods definition missing for SOL good: {good}")
        mnt_price = _default_price(mnt_blocks[good].body, good)
        vanilla_price = vanilla_prices[good]
        quantities[good] = {
            pop_type: _round_quantity(target[pop_type] * vanilla_price / mnt_price)
            for pop_type in POP_TYPES
        }

    grain_prices = {good: _default_price(mnt_blocks[good].body, good) for good in GRAINS}
    for pop_type in POP_TYPES:
        sol_spending = sum(
            sol_targets[good][pop_type] * vanilla_prices[good] for good in GRAINS
        )
        equal_quantity = _round_quantity(sol_spending / sum(grain_prices.values()))
        for good in GRAINS:
            quantities[good][pop_type] = equal_quantity

    if quantities["tools"]["laborers"] != Decimal("0.00050"):
        raise ValueError(
            "tools laborer compatibility quantity must be 0.0005, got "
            f"{quantities['tools']['laborers']}"
        )
    return quantities


def _render_demand_block(
    quantities: Dict[str, Decimal],
    slave_quantity: Decimal,
) -> str:
    lines = ["\tdemand_add = {"]
    for pop_type in ALL_POP_TYPES:
        value = slave_quantity if pop_type == "slaves" else quantities[pop_type]
        if value == 0:
            continue
        lines.append(f"\t\t{pop_type} = {_format_decimal(value)}")
    lines.append("\t}")
    return "\n".join(lines)


def _insert_after_default_price(body: str, demand_block: str, key: str) -> str:
    matches = list(
        re.finditer(
            r"(?m)^[ \t]*default_market_price\s*=\s*[^\r\n]+(?:\r?\n|$)",
            body,
        )
    )
    matches = [
        match
        for match in matches
        if body[: match.start()].count("{") - body[: match.start()].count("}") == 0
    ]
    if len(matches) != 1:
        raise ValueError(f"Expected one default price line for {key}, found {len(matches)}")
    insert_at = matches[0].end()
    prefix = "" if body[insert_at:insert_at + 1] in {"", "\n", "\r"} else "\n"
    return body[:insert_at] + prefix + demand_block + "\n" + body[insert_at:]


def _normalize_without_demand(body: str) -> str:
    stripped = _remove_fields(body, DEMAND_FIELDS)
    return "\n".join(line.rstrip() for line in stripped.splitlines() if line.strip()).strip()


def _render_goods(
    sol_targets: Dict[str, Dict[str, Decimal]],
    quantities: Dict[str, Dict[str, Decimal]],
    mnt_blocks: Dict[str, Block],
) -> str:
    lines = [
        GENERATED_HEADER.rstrip(),
        "# M&T owns every non-demand field. SOL owns the seven calibrated pop quantities.",
        "# Wealth and development demand gates remain removed for SOL's continuous scaling.",
    ]
    for good in sol_targets:
        original = mnt_blocks[good].body
        mnt_pop_demand = _final_pop_demand(original)
        base = _remove_fields(original, DEMAND_FIELDS)
        demand_block = _render_demand_block(quantities[good], mnt_pop_demand["slaves"])
        rendered = _insert_after_default_price(base, demand_block, good)
        if _normalize_without_demand(rendered) != _normalize_without_demand(original):
            raise ValueError(f"Non-demand M&T fields changed while rendering {good}")
        if re.search(r"\b(?:development_threshold|wealth_impact_threshold)\s*=", rendered):
            raise ValueError(f"Demand threshold survived compatibility rendering for {good}")
        lines.extend(["", f"REPLACE:{good} = {{{rendered}}}"])
    lines.append("")
    return "\n".join(lines)


def _validate_demand_invariants(
    sol_targets: Dict[str, Dict[str, Decimal]],
    quantities: Dict[str, Dict[str, Decimal]],
    vanilla_prices: Dict[str, Decimal],
    mnt_blocks: Dict[str, Block],
) -> None:
    for good, target in sol_targets.items():
        if good in GRAINS:
            continue
        mnt_price = _default_price(mnt_blocks[good].body, good)
        for pop_type in POP_TYPES:
            ideal = target[pop_type] * vanilla_prices[good] / mnt_price
            if abs(quantities[good][pop_type] - ideal) > QUANTUM / 2:
                raise ValueError(f"Rounded compatibility quantity is out of range: {good}/{pop_type}")

    grain_prices = {good: _default_price(mnt_blocks[good].body, good) for good in GRAINS}
    for pop_type in POP_TYPES:
        grain_values = {quantities[good][pop_type] for good in GRAINS}
        if len(grain_values) != 1:
            raise ValueError(f"Grain quantities are not equal for {pop_type}: {grain_values}")
        sol_spending = sum(
            sol_targets[good][pop_type] * vanilla_prices[good] for good in GRAINS
        )
        compat_spending = sum(
            quantities[good][pop_type] * grain_prices[good] for good in GRAINS
        )
        max_rounding_drift = sum(grain_prices.values()) * QUANTUM / 2
        if abs(sol_spending - compat_spending) > max_rounding_drift:
            raise ValueError(f"Grain spending drift exceeds fixed-point rounding for {pop_type}")


def _render_values_and_refresh(
    quantities: Dict[str, Dict[str, Decimal]],
    mnt_blocks: Dict[str, Block],
) -> Tuple[str, str]:
    rows = [
        (
            good,
            float(_default_price(mnt_blocks[good].body, good)),
            {pop_type: float(quantities[good][pop_type]) for pop_type in POP_TYPES},
        )
        for good in sorted(quantities)
    ]
    values = _generate_values(rows)
    values = values.replace(
        "# @AUTOGENERATED by scripts/gen_market_unit_consumption.py - do not edit; run script to regenerate.\n",
        GENERATED_HEADER,
        1,
    )
    values = values.replace(
        "# Generated from data/demand_price_table.csv. Each value is net\n"
        "# demand_add quantity for one pop type and one good, with duplicate\n"
        "# legacy demand-group rows counted once. Yearly market spending\n"
        "# multiplies these quantities by min(market_price, default_price).\n",
        "# Replaces full-SOL unit quantities with the final M&T-price-scaled matrix.\n"
        "# Yearly market spending multiplies them by min(market_price, default_price).\n",
        1,
    )
    values = re.sub(
        r"(?m)^(sol_unit_consumption_[A-Za-z0-9_]+)\s*=",
        r"REPLACE:\1 =",
        values,
    )

    refresh = _generate_refresh_block(rows)
    refresh = refresh.replace(
        "sol_refresh_market_pop_demand_maps = {",
        "REPLACE:sol_refresh_market_pop_demand_maps = {",
        1,
    )
    return values, refresh


def _render_authority_objects(
    sol_source: Path,
    vanilla_root: Path,
    mnt_root: Path,
    purpose: str,
) -> str:
    sol_blocks = [block for block in _blocks_in_file(sol_source) if block.operation]
    vanilla_blocks = _blocks_in_tree(vanilla_root)
    mnt_blocks = _blocks_in_tree(mnt_root)
    lines = [GENERATED_HEADER.rstrip(), purpose]
    seen: set[str] = set()
    for sol_block in sol_blocks:
        if sol_block.key in seen:
            raise ValueError(f"Duplicate SOL authority key in {sol_source}: {sol_block.key}")
        seen.add(sol_block.key)
        mnt_block = _optional_unique_block(mnt_blocks, sol_block.key, "M&T authority")
        vanilla_block = _optional_unique_block(vanilla_blocks, sol_block.key, "vanilla authority")
        authority = mnt_block or vanilla_block
        if authority is None:
            lines.extend(
                [
                    "",
                    f"# {sol_block.key}: absent from checked vanilla and M&T references; SOL TRY operation is inert.",
                ]
            )
            continue
        source_label = "M&T" if mnt_block else "vanilla"
        lines.extend(
            [
                "",
                f"# {source_label} authority: {authority.source.relative_to(REPO_ROOT)}",
                f"REPLACE:{sol_block.key} = {{{authority.body}}}",
            ]
        )
    lines.append("")
    return "\n".join(lines)


def _replace_once(text: str, old: str, new: str, label: str) -> str:
    count = text.count(old)
    if count != 1:
        raise ValueError(f"Expected one {label} anchor, found {count}")
    return text.replace(old, new, 1)


def _strip_epbm_instrumentation(body: str) -> str:
    lines = body.splitlines(keepends=True)
    stripped: List[str] = []
    skipping = False
    for line in lines:
        if "# SOL_MNT_BEGIN" in line:
            if skipping:
                raise ValueError("Nested SOL_MNT instrumentation markers")
            skipping = True
            continue
        if "# SOL_MNT_END" in line:
            if not skipping:
                raise ValueError("Unmatched SOL_MNT instrumentation end marker")
            skipping = False
            continue
        if not skipping:
            stripped.append(line)
    if skipping:
        raise ValueError("Unclosed SOL_MNT instrumentation marker")
    return "".join(stripped)


