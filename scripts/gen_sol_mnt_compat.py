    block = _unique_block(_blocks_in_file(path), key, "SOL retained action")
    body, count = re.subn(r"(?m)^[ \t]*sol_as_is_on\s*=\s*no[^\r\n]*(?:\r?\n|$)", "", block.body)
    if count != 1:
        raise ValueError(f"Expected one sol_as_is_on bypass in {key}, found {count}")
    return "\n".join(
        [
            GENERATED_HEADER.rstrip(),
            purpose,
            f"REPLACE:{key} = {{{body}}}",
            "",
        ]
    )


