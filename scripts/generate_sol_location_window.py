#!/usr/bin/env python3
"""
Generate the SOL standalone location window override from the Glorp UI 1.4 reference.

The generated file is Glorp UI 1.4 `location_window.gui` plus optional Great Projects
references and the two SOL touch points needed by the standalone UI:
  1. use local_sol_total_income for the income display
  2. add the SOL living-standard tooltip button in the location stat row
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from location_window_integrations import add_great_projects
from sync_location_window import LEGACY_GUI_MARKERS

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATH = REPO_ROOT / ".eu5-base" / "reference_mods" / "3601047146" / "in_game" / "gui" / "location_window.gui"
TARGET_PATH = REPO_ROOT / "src" / "sol_standalone" / "in_game" / "gui" / "location_window.gui"

AUTOGENERATED_HEADER = (
    "# @AUTOGENERATED by scripts/generate_sol_location_window.py - do not edit; "
    "source is Glorp UI 1.4 location_window.gui plus SOL and optional GP references.\n"
)

VANILLA_INCOME = 'raw_text = "[Location.GetTotalIncome|g2]@income!"'
SOL_INCOME = 'raw_text = "[Location.MakeScope.ScriptValue(\'local_sol_total_income\')|g2]@income!"'

BUTTON_ANCHOR_RE = re.compile(
    r"(?m)^(?P<indent>[ \t]*)expand = \{\}[ \t]*\r?\n"
    r"(?:[ \t]*\r?\n)*(?P=indent)subheader_unified_icon = \{[ \t]*\r?\n"
    r'[ \t]+visible = "\[HasPopBreakdownIntelOn\(Location\.Self\)\]"'
)

SOL_BUTTON = """							# SOL standalone insertion: shared location living-standard button.
							sol_location_living_standard_button = {}

"""


def generate() -> str:
    if not SOURCE_PATH.exists():
        raise FileNotFoundError(f"Reference file not found: {SOURCE_PATH}")

    text = SOURCE_PATH.read_text(encoding="utf-8-sig")
    stale = [marker for marker in LEGACY_GUI_MARKERS if marker in text]
    if stale:
        raise RuntimeError(f"Glorp UI location window contains legacy GUI markers: {stale}")

    income_count = text.count(VANILLA_INCOME)
    if income_count != 1:
        raise RuntimeError(
            f"Expected exactly one vanilla income anchor, found {income_count}: {VANILLA_INCOME}"
        )
    text = text.replace(VANILLA_INCOME, SOL_INCOME, 1)

    anchor_matches = list(BUTTON_ANCHOR_RE.finditer(text))
    if len(anchor_matches) != 1:
        raise RuntimeError(
            "Expected exactly one SOL button insertion anchor after average satisfaction in the migration stat row, "
            f"found {len(anchor_matches)}."
        )
    match = anchor_matches[0]
    indent = match.group("indent")
    button = f"{indent}# SOL standalone insertion: shared location living-standard button.\n{indent}sol_location_living_standard_button = {{}}\n\n"
    insert_at = match.start()
    text = text[:insert_at] + button + text[insert_at:]

    return AUTOGENERATED_HEADER + add_great_projects(text, expected_queue_actions=6)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="Return non-zero if the target does not match the generated output.",
    )
    args = parser.parse_args()

    generated = generate()

    if args.check:
        if not TARGET_PATH.exists():
            print(f"[FAIL] Missing generated target: {TARGET_PATH.relative_to(REPO_ROOT)}")
            return 1
        current = TARGET_PATH.read_text(encoding="utf-8-sig")
        if current != generated:
            print(f"[FAIL] Out of date: {TARGET_PATH.relative_to(REPO_ROOT)}")
            print(f"       Run: $env:PYTHONUTF8='1'; & $env:EU5_PYTHON scripts/generate_sol_location_window.py")
            return 1
        print(f"[OK] Up to date: {TARGET_PATH.relative_to(REPO_ROOT)}")
        return 0

    TARGET_PATH.parent.mkdir(parents=True, exist_ok=True)
    TARGET_PATH.write_text(generated, encoding="utf-8")
    print(f"[OK] Generated {TARGET_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
